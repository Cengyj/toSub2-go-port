const maxAuthListBytes = 8 << 20

var ErrInvalidAuthList = errors.New("CPA 授权状态响应无效")

// RemoteAuthFile contains only the metadata needed to reconcile a locally
// owned authorization. Upstream diagnostics, paths and tokens stay private.
type RemoteAuthFile struct {
	Filename     string
	Email        string
	AccountID    string
	PlanType     string
	NeedsRelogin bool
}

// MatchesIdentity requires the stable filename generated by this application.
// Optional identity evidence returned by CPA must agree with the local grant;
// email alone never grants ownership of someone else's remote authorization.
func (f RemoteAuthFile) MatchesIdentity(email, accountID string) bool {
	email, accountID = strings.TrimSpace(email), strings.TrimSpace(accountID)
	return validEmail(email) && validIdentifier(accountID) &&
		f.Filename == authFilename(email, accountID) &&
		(f.Email == "" || strings.EqualFold(f.Email, email)) &&
		(f.AccountID == "" || f.AccountID == accountID)
}

type authListError struct{ cause error }

func (e *authListError) Error() string { return SafeListError(e.cause) }
func (e *authListError) Unwrap() error { return e.cause }

// SafeListError never includes remote content, request URLs or credentials.
func SafeListError(err error) string {
	if err == nil {
		return ""
	}
	for _, known := range []error{ErrInvalidBaseURL, ErrInvalidAPIKey, ErrInvalidPriority, ErrInvalidWeight, ErrInvalidAuthList} {
		if errors.Is(err, known) {
			return known.Error()
		}
	}
	var remote *RemoteError
	if errors.As(err, &remote) {
		return remote.Error()
	}
	if errors.Is(err, context.Canceled) {
		return "CPA 状态读取已取消"
	}
	if errors.Is(err, context.DeadlineExceeded) {
		return "CPA 状态读取超时"
	}
	return "CPA 状态读取失败"
}

// ListAuthFiles reads CPA's v0 management listing without following redirects.
// Only this tool's Codex files are returned. The legacy disk-only response has
// no status evidence, so it can never independently trigger a relogin.
func (c *Client) ListAuthFiles(ctx context.Context) ([]RemoteAuthFile, error) {
	if ctx == nil {
		ctx = context.Background()
	}
	if err := ctx.Err(); err != nil {
		return nil, &authListError{err}
	}
	if c == nil {
		return nil, &authListError{ErrInvalidBaseURL}
	}
	cfg, err := validateConfig(c.cfg)
	if err != nil {
		return nil, &authListError{err}
	}
	headers := make(http.Header)
	headers.Set("Authorization", "Bearer "+cfg.APIKey)
	headers.Set("Accept", "application/json")
	response, err := transport.DoHTTPWithRetry(ctx, c.http, transport.Request{
		Method: http.MethodGet, URL: cfg.BaseURL + "/v0/management/auth-files", Headers: headers,
		Timeout: cfg.Timeout, SingleAttempt: true,
	}, maxAuthListBytes, 0, 0, nil)
	if err != nil {
		return nil, &authListError{err}
	}
	if response.StatusCode != http.StatusOK {
		return nil, &authListError{&RemoteError{StatusCode: response.StatusCode}}
	}
	files, err := parseAuthList(response.Body)
	if err != nil {
		return nil, &authListError{ErrInvalidAuthList}
	}
	return files, nil
}

type remoteAuthWire struct {
	Name           string `json:"name"`
	Type           string `json:"type"`
	Provider       string `json:"provider"`
	Email          string `json:"email"`
	AccountID      string `json:"account_id"`
	ChatGPTID      string `json:"chatgpt_account_id"`
	PlanType       string `json:"plan_type"`
	Status         string `json:"status"`
	StatusMessage  string `json:"status_message"`
	Disabled       bool   `json:"disabled"`
	RuntimeOnly    bool   `json:"runtime_only"`
	Source         string `json:"source"`
	RequiresSignIn bool   `json:"requires_sign_in"`
	QuotaBlocked   bool   `json:"quota_blocked"`
	RecoveryStage  string `json:"recovery_stage"`
	IDToken        struct {
		Email     string `json:"email"`
		AccountID string `json:"chatgpt_account_id"`
		PlanType  string `json:"plan_type"`
	} `json:"id_token"`
	RefreshError struct {
		Code       string `json:"code"`
		Message    string `json:"message"`
		HTTPStatus int    `json:"http_status"`
	} `json:"refresh_error"`
}

func parseAuthList(data []byte) ([]RemoteAuthFile, error) {
	if len(data) > maxAuthListBytes || authmaterial.ValidateUnambiguousJSON(data) != nil {
		return nil, ErrInvalidAuthList
	}
	var envelope map[string]json.RawMessage
	if json.Unmarshal(data, &envelope) != nil || envelope == nil || !uniqueFoldedKeys(envelope) {
		return nil, ErrInvalidAuthList
	}
	var entries []json.RawMessage
	if json.Unmarshal(envelope["files"], &entries) != nil || entries == nil {
		return nil, ErrInvalidAuthList
	}
	files := make([]RemoteAuthFile, 0, len(entries))
	seen := make(map[string]bool)
	for _, entry := range entries {
		var fields map[string]json.RawMessage
		if json.Unmarshal(entry, &fields) != nil || fields == nil || !uniqueFoldedKeys(fields) {
			return nil, ErrInvalidAuthList
		}
		var header struct {
			Name string `json:"name"`
		}
		if json.Unmarshal(entry, &header) != nil {
			return nil, ErrInvalidAuthList
		}
		if !ownedAuthFilename(header.Name) {
			continue
		}
		if seen[header.Name] {
			return nil, ErrInvalidAuthList
		}
		seen[header.Name] = true
		// Reject aliases before Go's case-insensitive struct decoder can choose
		// between conflicting identity or recovery fields.
		for _, key := range []string{"id_token", "refresh_error"} {
			for name, value := range fields {
				if strings.EqualFold(name, key) && string(value) != "null" {
					var nested map[string]json.RawMessage
					if json.Unmarshal(value, &nested) != nil || nested == nil || !uniqueFoldedKeys(nested) {
						return nil, ErrInvalidAuthList
					}
				}
			}
		}
		var raw remoteAuthWire
		if json.Unmarshal(entry, &raw) != nil {
			return nil, ErrInvalidAuthList
		}
		provider, err := consistentValue(true, raw.Type, raw.Provider)
		if err != nil || !strings.EqualFold(provider, "codex") {
			continue
		}
		email, emailErr := consistentValue(true, raw.Email, raw.IDToken.Email)
		accountID, accountErr := consistentValue(false, raw.AccountID, raw.ChatGPTID, raw.IDToken.AccountID)
		plan, planErr := consistentValue(true, raw.PlanType, raw.IDToken.PlanType)
		if emailErr != nil || accountErr != nil || planErr != nil || email != "" && !validEmail(email) || accountID != "" && !validIdentifier(accountID) || len(plan) > 64 || strings.ContainsAny(plan, "\r\n\x00") {
			continue
		}
		files = append(files, RemoteAuthFile{
			Filename: raw.Name, Email: strings.ToLower(email), AccountID: accountID,
			PlanType: strings.ToLower(plan), NeedsRelogin: remoteNeedsRelogin(raw),
		})
	}
	return files, nil
}

func uniqueFoldedKeys(fields map[string]json.RawMessage) bool {
	seen := make(map[string]bool, len(fields))
	for key := range fields {
		key = strings.ToLower(key)
		if seen[key] {
			return false
		}
		seen[key] = true
	}
	return true
}

func ownedAuthFilename(name string) bool {
	const prefix = "tosub2-codex-"
	if !strings.HasPrefix(name, prefix) || !strings.HasSuffix(name, ".json") || len(name) != len(prefix)+64+len(".json") {
		return false
	}
	digest := strings.TrimSuffix(strings.TrimPrefix(name, prefix), ".json")
	_, err := hex.DecodeString(digest)
	return err == nil && strings.ToLower(digest) == digest
}

var authFailureCode = regexp.MustCompile(`\b(invalid_grant|refresh_token_(invalid|invalidated|expired|reused|revoked)|token_(expired|revoked)|invalid_token|invalid_auth_token)\b`)
var nonAuthHTTPStatus = regexp.MustCompile(`\b(403|429|5[0-9]{2})\b`)

func remoteNeedsRelogin(raw remoteAuthWire) bool {
	if raw.Disabled || raw.RuntimeOnly || !strings.EqualFold(strings.TrimSpace(raw.Status), "error") || strings.EqualFold(strings.TrimSpace(raw.Source), "memory") || raw.QuotaBlocked || strings.EqualFold(raw.RecoveryStage, "quota_blocked") {
		return false
	}
	message := strings.ToLower(strings.TrimSpace(raw.StatusMessage))
	evidence := message + " " + strings.ToLower(raw.RefreshError.Code) + " " + strings.ToLower(raw.RefreshError.Message)
	// An unrelated failure must never launch credential automation, even when
	// a diagnostic also quotes an earlier authorization failure.
	for _, excluded := range []string{"quota", "rate limit", "rate_limit", "too many requests", "banned", "deactivated", "suspended", "account_disabled", "account disabled", "account_closed", "account closed", "forbidden", "payment", "billing", "timeout", "timed out", "connection", "network", "server_error", "service_unavailable", "bad_gateway", "refresh_outcome_unknown"} {
		if strings.Contains(evidence, excluded) {
			return false
		}
	}
	if nonAuthHTTPStatus.MatchString(evidence) || raw.RefreshError.HTTPStatus == 403 || raw.RefreshError.HTTPStatus == 429 || raw.RefreshError.HTTPStatus >= 500 {
		return false
	}
	if raw.RequiresSignIn || authFailureCode.MatchString(evidence) {
		return true
	}
	switch message {
	case "unauthorized", "unauthorized (refresh token invalid)", "token expired", "access token expired", "refresh token expired", "invalid or expired token", "invalid token", "401 unauthorized":
		return true
	}
	return false
}
